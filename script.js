document.addEventListener("DOMContentLoaded", () => {
  const initialLang = localStorageSafeGet("lang") || "es";
  applyTranslations(initialLang);

  // language toggle
  document.getElementById("lang-toggle").addEventListener("click", () => {
    const next = document.documentElement.lang === "es" ? "en" : "es";
    setLanguage(next);
  });

  // mobile menu
  const menuToggle = document.getElementById("menu-toggle");
  const tabs = document.getElementById("tabs");
  menuToggle.addEventListener("click", () => {
    const isOpen = tabs.classList.toggle("active");
    menuToggle.setAttribute("aria-expanded", String(isOpen));
  });
  tabs.querySelectorAll(".tab").forEach((tab) => {
    tab.addEventListener("click", () => {
      tabs.classList.remove("active");
      menuToggle.setAttribute("aria-expanded", "false");
    });
  });

  // scrollspy: highlight the active tab as sections pass
  const sections = Array.from(document.querySelectorAll("main > section[id]"));
  const tabLinks = Array.from(document.querySelectorAll(".tab"));
  const spy = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          tabLinks.forEach((t) => t.classList.remove("active"));
          const match = document.querySelector(`.tab[data-section="${entry.target.id}"]`);
          if (match) match.classList.add("active");
        }
      });
    },
    { rootMargin: "-45% 0px -50% 0px", threshold: 0 }
  );
  sections.forEach((s) => spy.observe(s));

  // reveal-on-scroll
  const revealObserver = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("in-view");
          revealObserver.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.15 }
  );
  document.querySelectorAll(".reveal").forEach((el) => revealObserver.observe(el));

  // hero intro sequence (skipped entirely under prefers-reduced-motion)
  const prefersReducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  if (!prefersReducedMotion) {
    const codeLines = document.querySelectorAll(".code-card .code-line");
    codeLines.forEach((line, i) => {
      line.style.opacity = "0";
      line.style.transform = "translateY(4px)";
      line.style.transition = "opacity 0.35s ease, transform 0.35s ease";
      setTimeout(() => {
        line.style.opacity = "1";
        line.style.transform = "translateY(0)";
      }, 120 + i * 90);
    });

    const heroText = document.querySelector(".hero-text");
    heroText.style.opacity = "0";
    heroText.style.transform = "translateY(10px)";
    heroText.style.transition = "opacity 0.5s ease, transform 0.5s ease";
    setTimeout(() => {
      heroText.style.opacity = "1";
      heroText.style.transform = "translateY(0)";
    }, 120 + codeLines.length * 90 + 150);
  }
});
