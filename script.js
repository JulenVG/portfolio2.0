function applyTranslations(lang) {
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-translate]").forEach((el) => {
    const key = el.getAttribute("data-translate");
    if (translations[lang][key] !== undefined) {
      el.innerHTML = translations[lang][key];
    }
  });

  document.querySelectorAll("[data-translate-html]").forEach((el) => {
    const key = el.getAttribute("data-translate-html");
    const items = translations[lang][key];
    if (Array.isArray(items)) {
      el.innerHTML = items.map((line) => `<li>${line}</li>`).join("");
    }
  });

  const current = document.getElementById("lang-current");
  const other = document.getElementById("lang-other");
  if (current && other) {
    current.textContent = lang.toUpperCase();
    other.textContent = lang === "es" ? "EN" : "ES";
  }
}

function setLanguage(lang) {
  applyTranslations(lang);
  localStorageSafeSet("lang", lang);
}

// Storage can throw in some sandboxed/privacy contexts — never let it break the page.
function localStorageSafeSet(key, value) {
  try {
    window.localStorage.setItem(key, value);
  } catch (e) {
    /* ignore */
  }
}
function localStorageSafeGet(key) {
  try {
    return window.localStorage.getItem(key);
  } catch (e) {
    return null;
  }
}

